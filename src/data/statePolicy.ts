export function getStatePolicy(stateNameOrSlug: string): StatePolicy | undefined {
  if (!stateNameOrSlug) return undefined;
  
  // Direct match by state name
  if (STATE_POLICIES[stateNameOrSlug]) {
    return STATE_POLICIES[stateNameOrSlug];
  }

  // Match by slug or case-insensitive name
  const normalized = stateNameOrSlug.trim().toLowerCase().replace(/-/g, " ");
  for (const policy of Object.values(STATE_POLICIES)) {
    if (
      policy.name.toLowerCase() === normalized ||
      policy.slug === stateNameOrSlug.toLowerCase()
    ) {
      return policy;
    }
  }

  return undefined;
}

/**
 * Calculates theoretical annual rainwater catchment yield in gallons.
 * Formula: Gallons = Square Footage × Annual Rainfall (inches) × 0.6233 × Efficiency
 *
 * @param sqFt Catchment area in square feet
 * @param rainfallInches Average annual rainfall in inches
 * @param efficiency Runoff efficiency coefficient (default 0.90 for standard pitched roofs)
 */
export function calculateAnnualYield(
  sqFt: number,
  rainfallInches: number,
  efficiency = 0.90
): number {
  if (sqFt <= 0 || rainfallInches <= 0) return 0;
  return Math.round(sqFt * rainfallInches * 0.6233 * efficiency);
}
